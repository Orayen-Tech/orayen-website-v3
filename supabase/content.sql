create table if not exists public.portfolios (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  category text not null,
  title text not null,
  description text not null,
  image text not null,
  alt text not null,
  display_order integer not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.portfolios enable row level security;

create index if not exists portfolios_published_order_idx
  on public.portfolios (display_order)
  where is_published = true;

do $$
begin
  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'portfolios'
      and policyname = 'Public can read published portfolios'
  ) then
    create policy "Public can read published portfolios"
      on public.portfolios
      for select
      to anon, authenticated
      using (is_published = true);
  end if;
end
$$;

